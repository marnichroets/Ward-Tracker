@app.post("/api/campaigns/{campaign_id}/activities/repeat")
async def create_campaign_activity_repeat(campaign_id: str, body: CampaignActivityRepeatIn):
    campaign, owner_person_id = await require_campaign_owner(campaign_id, body.person_id)
    reject_if_archived(campaign)
    roster_person = await require_roster_person(owner_person_id)

    if body.weekday not in DAY_OFFSET:
        raise HTTPException(400, "Invalid weekday")
    try:
        first_date = date.fromisoformat(body.first_occurrence_date)
    except (TypeError, ValueError):
        raise HTTPException(400, "first_occurrence_date must be an ISO calendar date")
    if DAY_ORDER[first_date.weekday()] != body.weekday:
        raise HTTPException(400, "first_occurrence_date does not fall on the given weekday")
    try:
        until = date.fromisoformat(body.until)
    except (TypeError, ValueError):
        raise HTTPException(400, "until must be an ISO calendar date")

    try:
        validate_campaign_activity_date(campaign["start_date"], campaign["end_date"], body.first_occurrence_date)
    except ValueError as exc:
        raise HTTPException(400, str(exc))
    if until < first_date:
        raise HTTPException(400, "until must be on or after first_occurrence_date")

    # Clamp to the campaign's own end date — a client-supplied `until`
    # further out never generates occurrences past the campaign's range.
    campaign_end = date.fromisoformat(campaign["end_date"])
    effective_until = min(until, campaign_end)

    recurrence_id = compute_recurrence_id(campaign_id, body)
    created_ids: list[str] = []
    skipped_dates: list[str] = []

    d = first_date
    while d <= effective_until:
        existing = await entries_col.find_one({
            "recurrence_id": recurrence_id,
            "activity_date": d.isoformat(),
        })
        if existing:
            skipped_dates.append(d.isoformat())
        else:
            doc = campaign_activity_base_doc(
                roster_person, campaign_id, d,
                body.type, body.type_display, body.notes,
                body.start_time, body.end_time, body.venue,
            )
            doc["recurrence_id"] = recurrence_id
            doc["submitted_at"] = datetime.now(timezone.utc).isoformat()
            try:
                res = await entries_col.insert_one(doc)
                created_ids.append(str(res.inserted_id))
            except DuplicateKeyError:
                # Race-condition backstop: the partial unique index catches
                # a concurrent identical retry that slipped past the
                # find_one check above.
                skipped_dates.append(d.isoformat())
        d += timedelta(days=7)

    return {
        "recurrence_id": recurrence_id,
        "created": created_ids,
        "skipped_duplicate_dates": skipped_dates,
    }


