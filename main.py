async def validate_evidence_refs_for_person(refs: list[dict], person_id: str) -> None:
    if not refs:
        raise HTTPException(400, "Please add at least one photo before submitting this activity.")
    for ref in refs:
        try:
            oid = ObjectId(ref["id"])
            stream = await evidence_bucket.open_download_stream(oid)
        except Exception:
            raise HTTPException(400, "Photo evidence could not be found. Please upload it again.")
        metadata = getattr(stream, "metadata", {}) or {}
        if metadata.get("owner_person_id") != person_id:
            raise HTTPException(400, "Photo evidence does not match this candidate.")


async def validate_participant_ids(ids: list[str]) -> None:
    if not ids:
        return
    found = {
        doc.get("name_slug")
        async for doc in roster_col.find({"name_slug": {"$in": ids}}, {"name_slug": 1})
    }
    if any(pid not in found for pid in ids):
        raise HTTPException(400, "One or more selected roster participants could not be found.")


def normalize_name_words(name: str) -> set:
    # Strips titles like "(CLLR)" so a name typed without middle names/suffixes
    # still matches its fuller roster form.
    name = re.sub(r"\([^)]*\)", "", name)
    name = re.sub(r"[^a-z0-9\s]", "", name.lower())
    return set(w for w in name.split() if w)


def names_match(a: str, b: str) -> bool:
    words_a, words_b = normalize_name_words(a), normalize_name_words(b)
    if not words_a or not words_b:
        return False
    return words_a <= words_b or words_b <= words_a


async def resolve_and_canonicalize_person(body: "EntryIn") -> None:
    """Validate the submitted candidate against the official roster and replace
    whatever name/ward/person_id the client sent with the roster's canonical
    values. This is the backend enforcement point: it runs for every entry
    create/update regardless of whether the request came through the UI, so a
    direct API call cannot invent a new person or attach itself to the wrong
    roster identity by spelling/case/abbreviation variation."""
    roster_person = await roster_col.find_one({"name_slug": slugify(body.name)})
    if not roster_person:
        raise HTTPException(400, "Please select your name from the roster.")
    body.name = roster_person["name"]
    body.ward = roster_person.get("ward", "")
    body.person_id = roster_person["name_slug"]


async def resolve_campaign_person_id(person_id: str) -> str:
    """Same roster-only identity enforcement as entries: a campaign may only
    belong to an actual roster person. `person_id` here is whatever identity
    string the client is currently using (today's frontend always sends the
    slug of the selected roster person's canonical name, which already
    equals that roster entry's name_slug) — re-slugifying it is a no-op for
    an already-canonical slug and correctly resolves a raw name too. The
    client-sent value is never trusted directly; only the roster's own
    name_slug is stored, exactly as resolve_and_canonicalize_person does for
    entries."""
    roster_person = await roster_col.find_one({"name_slug": slugify(person_id)})
    if not roster_person:
        raise HTTPException(400, "Please select your name from the roster.")
    return roster_person["name_slug"]


def campaign_doc_from_body(body: "CampaignIn") -> dict:
    """Deliberately excludes person_id: ownership is resolved and applied
    separately by each route (set once at create, never accepted from an
    update body afterwards), so a mutable field never sneaks back in here."""
    name = (body.name or "").strip()
    if not name:
        raise HTTPException(400, "Campaign name is required")
    try:
        start, end = validate_campaign_date_range(body.start_date, body.end_date)
    except ValueError as exc:
        raise HTTPException(400, str(exc))
    doc = {
        "name": name,
        "start_date": start.isoformat(),
        "end_date": end.isoformat(),
    }
    doc["purpose"] = (body.purpose or "").strip()
    return doc


def derive_campaign_status(doc: dict, now: Optional[datetime] = None) -> str:
    """Planned/active/completed are pure functions of today vs the stored
    dates and are deliberately NOT persisted, so they can never drift out of
    sync with the calendar. archived_at is the only stored, manual state."""
    if doc.get("archived_at"):
        return "archived"
    today = sast_today(now)
    start = date.fromisoformat(doc["start_date"])
    end = date.fromisoformat(doc["end_date"])
    if today < start:
        return "planned"
    if today > end:
        return "completed"
    return "active"


def campaign_for_response(doc: dict) -> dict:
    doc = oid_str(doc)
    doc["status"] = derive_campaign_status(doc)
    return doc


async def require_campaign_owner(campaign_id: str, person_id: str) -> tuple[dict, str]:
    """Resolve the caller's claimed identity against the roster (rejecting an
    unknown identity exactly like create_campaign does), then load the
    campaign only if it belongs to that resolved identity. A campaign that
    exists but belongs to someone else is deliberately indistinguishable
    from one that doesn't exist (404) — the same convention update_entry/
    delete_entry already use for person-scoped entries, so a wrong guess at
    someone else's campaign_id never confirms it exists or reveals its
    owner. There is no admin bypass here; this is candidate-facing only."""
    owner_person_id = await resolve_campaign_person_id(person_id)
    doc = await campaigns_col.find_one({"_id": ObjectId(campaign_id), "person_id": owner_person_id})
    if not doc:
        raise HTTPException(404, "Campaign not found")
    return doc, owner_person_id


async def require_roster_person(person_id: str) -> dict:
    """Fetch the full roster document for an already-resolved name_slug.
    Used right after require_campaign_owner, which only returns the slug —
    kept as a separate small lookup rather than changing that function's
    signature, so Phase 1's already-verified ownership checks stay untouched."""
    roster_person = await roster_col.find_one({"name_slug": person_id})
    if not roster_person:
        raise HTTPException(400, "Please select your name from the roster.")
    return roster_person


def reject_if_archived(
    campaign: dict, message: str = "Archived campaigns cannot accept new activities."
) -> None:
    """Archiving is the normal terminal action for a campaign — it must
    read as closed. This never deletes or modifies any existing activity;
    reads (GET .../activities) are always untouched. Phase 5 reuses this same
    guard (with a context-appropriate message) to also block editing the
    campaign itself and editing an activity that belongs to it — "archived"
    means frozen from every candidate mutation, not just new activities."""
    if campaign.get("archived_at"):
        raise HTTPException(409, message)


def campaign_activity_base_doc(
    roster_person: dict,
    campaign_id: str,
    activity_date: date,
    type_: str,
    type_display: str,
    notes: Optional[str],
    start_time: Optional[str],
    end_time: Optional[str],
    venue: Optional[str],
) -> dict:
    """Shared field-building for both single and repeat campaign-activity
    creation: derives week_key/day from the absolute date (campaign
    activities are dated directly, not picked via week_key+day), then
    reuses the exact same time/venue/Other/SmartSheet-classification logic
    every other activity goes through, so a campaign activity is
    indistinguishable in shape from a plain one anywhere it's displayed."""
    week_key, day = week_key_and_day_for_date(activity_date)
    doc = {
        "person_id": roster_person["name_slug"],
        "name": roster_person["name"],
        "ward": roster_person.get("ward", ""),
        "campaign_id": campaign_id,
        "day": day,
        "type": type_,
        "type_display": type_display,
        "notes": notes,
        "week_key": week_key,
        "week_label": format_week_label(week_key),
        "activity_date": activity_date.isoformat(),
    }
    try:
        doc["start_time"], doc["end_time"] = validate_time_range(start_time, end_time)
    except ValueError as exc:
        raise HTTPException(400, str(exc))
    doc["venue"] = normalise_venue(venue)
    # Always a creation path (single or repeat campaign activity) — location
    # is required and must not just restate the ward, same rule
    # entry_doc_from_body applies on its create branch.
    if not doc["venue"] or location_is_ward_only(doc["venue"], doc.get("ward")):
        raise HTTPException(400, LOCATION_REQUIRED_MESSAGE)
    if is_new_other_submission(doc):
        other_text = (doc.get("type_display") or "").strip()
        if not other_text:
            raise HTTPException(400, "Other activity text is required")
        doc["type_display"] = other_text
    doc.update(reporting_metadata_for_submission(doc))
    # Always a creation path (single or repeat campaign activity) — explicit
    # per CAMPAIGNS.md §4, same as entry_doc_from_body's create branch.
    doc["capture_status"] = official_capture.AWAITING_CAPTURE
    return doc


def compute_recurrence_id(campaign_id: str, body: "CampaignActivityRepeatIn") -> str:
    """Deterministic id for this repeat request's meaningful content. A
    byte-for-byte identical retry (same campaign/weekday/dates/type/time/
    venue) recomputes the same id, so the (recurrence_id, activity_date)
    check/index catches it as a duplicate. Any real difference — a
    different time, venue, or a separate recurring series — produces a
    different id, so two independently-created activities that merely
    share a type and date are never mistaken for the same occurrence."""
    raw = "|".join([
        campaign_id,
        body.weekday,
        body.first_occurrence_date,
        body.until,
        body.type,
        body.type_display,
        body.start_time or "",
        body.end_time or "",
        (body.venue or "").strip(),
    ])
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:24]


def _effective_activity_date(doc: dict) -> Optional[str]:
    """Same activity_date fallback enrich_entry uses for display, applied
    here purely for before/after comparison — never persisted."""
    if doc.get("activity_date"):
        return doc["activity_date"]
    if doc.get("week_key") and doc.get("day") in DAY_OFFSET:
        return activity_date_for_day(doc["week_key"], doc["day"])
    return None


def _apply_post_capture_edit_reset(existing_doc: dict, doc: dict) -> None:
    """Phase 5: a candidate edit to an activity the coordinator has already
    marked Captured may invalidate what was transcribed into the official
    Campaign Manager, so it must reopen for re-capture. Only a MEANINGFUL
    change — date, start/end time, venue, or the Ward Tracker activity type
    itself — does this; a notes-only edit or a PUT that resubmits identical
    values must never disturb an already-captured activity. Mutates `doc`
    in place by adding capture_status/captured_at/official_activity_type
    keys ONLY when a reset is actually warranted — otherwise `doc` gains no
    such keys, exactly like every other (non-captured) edit already worked
    before this phase, leaving update_entry_capture as the only other writer
    of these fields."""
    if official_capture.resolve_capture_status(existing_doc) != official_capture.CAPTURED:
        return
    schedule_or_location_changed = (
        _effective_activity_date(existing_doc) != doc.get("activity_date")
        or existing_doc.get("start_time") != doc.get("start_time")
        or existing_doc.get("end_time") != doc.get("end_time")
        or existing_doc.get("venue") != doc.get("venue")
    )
    type_changed = (
        existing_doc.get("type") != doc.get("type")
        or existing_doc.get("type_display") != doc.get("type_display")
    )
    if not (schedule_or_location_changed or type_changed):
        return
    doc["capture_status"] = official_capture.AWAITING_CAPTURE
    doc["captured_at"] = None
    if type_changed:
        # The source activity itself changed — the coordinator must
        # reconfirm the official type rather than keep a stale override.
        doc["official_activity_type"] = None


def entry_doc_from_body(
    body: "EntryIn", existing_doc: Optional[dict] = None, campaign: Optional[dict] = None
) -> dict:
    """`campaign` is only ever passed by update_entry, and only when the
    entry being edited already has a campaign_id — it's how an existing
    campaign-linked occurrence gets re-validated against its own campaign's
    date range on edit instead of the candidate current/next-week rule.
    Plain entries (campaign=None, the only case for create_entry) are
    completely unaffected — this is a separate branch, not a relaxation of
    validate_candidate_week_key."""
    doc = body.model_dump()
    doc["participant_ids"] = normalize_participant_ids(doc.get("participant_ids"))
    doc["other_participants"] = normalize_other_participants(doc.get("other_participants"))
    doc["evidence_photos"] = normalize_evidence_refs(doc.get("evidence_photos"))
    try:
        if campaign:
            activity_date = validate_campaign_activity_date(
                campaign["start_date"], campaign["end_date"], doc.get("activity_date") or ""
            )
            week_key, day = week_key_and_day_for_date(activity_date)
            doc["week_key"] = week_key
            doc["day"] = day
            doc["week_label"] = format_week_label(week_key)
            doc["activity_date"] = activity_date.isoformat()
        else:
            validate_candidate_week_key(doc["week_key"])
            doc["week_label"] = format_week_label(doc["week_key"])
            doc["activity_date"] = normalise_new_activity_date(
                doc["week_key"], doc["day"], doc.get("activity_date")
            )
        doc["start_time"], doc["end_time"] = validate_time_range(
            doc.get("start_time"), doc.get("end_time")
        )
        doc["venue"] = normalise_venue(doc.get("venue"))
        if existing_doc is None:
            # New activity only — an edit to a historical record (including
            # one with a legacy blank location) is never newly blocked by
            # this rule, matching the frontend's isNewEntry-only check.
            if not doc["venue"] or location_is_ward_only(doc["venue"], doc.get("ward")):
                raise ValueError(LOCATION_REQUIRED_MESSAGE)
            if campaign is None and not doc["evidence_photos"]:
                raise ValueError("Please add at least one photo before submitting this activity.")
        elif existing_doc.get("evidence_photos") and not doc["evidence_photos"]:
            raise ValueError("Activities with photo evidence must keep at least one photo.")
        if is_new_other_submission(doc):
            other_text = (doc.get("type_display") or "").strip()
            if not other_text:
                raise ValueError("Other activity text is required")
            doc["type_display"] = other_text
    except ValueError as exc:
        raise HTTPException(400, str(exc))
    if existing_doc and doc.get("notes") is None and existing_doc.get("notes"):
        doc["notes"] = existing_doc["notes"]
    doc.update(reporting_metadata_for_submission(doc, existing_doc))
    if existing_doc is None:
        # Explicit at creation (CAMPAIGNS.md §4) — not left to enrich_entry's
        # read-time default.
        doc["capture_status"] = official_capture.AWAITING_CAPTURE
    else:
        # An update's $set only ever includes capture_status/captured_at/
        # official_activity_type when a Captured activity was just
        # meaningfully edited (Phase 5) — otherwise none of those keys are
        # added here, so an awaiting/historical activity's capture state is
        # left completely untouched by editing it, exactly as before.
        _apply_post_capture_edit_reset(existing_doc, doc)
    return doc


def normalize_participant_ids(values: Optional[list]) -> list[str]:
    out = []
    seen = set()
    for value in values or []:
        text = str(value or "").strip()
        if text and text not in seen:
            out.append(text)
            seen.add(text)
    return out


def normalize_other_participants(values: Optional[list]) -> list[str]:
    out = []
    seen = set()
    for value in values or []:
        text = re.sub(r"\s+", " ", str(value or "").strip())
        key = text.casefold()
        if text and key not in seen:
            out.append(text)
            seen.add(key)
    return out


def evidence_url(photo_id: str) -> str:
    return f"/api/evidence/photos/{photo_id}"


def normalize_evidence_refs(values: Optional[list]) -> list[dict]:
    out = []
    seen = set()
    for value in values or []:
        ref = value.model_dump() if hasattr(value, "model_dump") else dict(value or {})
        photo_id = str(ref.get("id") or "").strip()
        if not photo_id or photo_id in seen:
            continue
        try:
            ObjectId(photo_id)
        except Exception:
            continue
        seen.add(photo_id)
        out.append({
            "id": photo_id,
            "filename": sanitize_filename(ref.get("filename") or "photo.jpg"),
            "content_type": str(ref.get("content_type") or "image/jpeg"),
            "size": int(ref.get("size") or 0),
            "url": evidence_url(photo_id),
        })
    return out


def sanitize_filename(filename: object) -> str:
    base = os.path.basename(str(filename or "photo.jpg")).strip()
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", base).strip(".-")
    return base or "photo.jpg"


def prepare_evidence_image(raw: bytes, original_filename: str) -> tuple[bytes, str, str, int, tuple[int, int]]:
    if not raw:
        raise HTTPException(400, "Photo file is empty.")
    if len(raw) > MAX_EVIDENCE_PHOTO_BYTES:
        raise HTTPException(400, "Photo is too large. Please choose a smaller image.")
    try:
        img = Image.open(io.BytesIO(raw))
        img.verify()
        img = Image.open(io.BytesIO(raw))
    except (UnidentifiedImageError, OSError):
        raise HTTPException(400, "Please upload a valid image file.")
    fmt = (img.format or "").upper()
    if fmt not in SUPPORTED_EVIDENCE_FORMATS:
        raise HTTPException(400, "Supported photo formats are JPEG, PNG and WEBP.")
    img = Image.open(io.BytesIO(raw))
    img.load()
    if max(img.size) > MAX_EVIDENCE_IMAGE_SIDE:
        img.thumbnail((MAX_EVIDENCE_IMAGE_SIDE, MAX_EVIDENCE_IMAGE_SIDE))
    if fmt == "PNG" and img.mode in {"RGBA", "LA"}:
        out = io.BytesIO()
        img.save(out, format="PNG", optimize=True)
        payload = out.getvalue()
        content_type = "image/png"
        ext = "png"
    else:
        if img.mode not in {"RGB", "L"}:
            img = img.convert("RGB")
        out = io.BytesIO()
        img.save(out, format="JPEG", quality=82, optimize=True)
        payload = out.getvalue()
        content_type = "image/jpeg"
        ext = "jpg"
    safe_name = sanitize_filename(original_filename)
    stem = os.path.splitext(safe_name)[0] or "photo"
    return payload, content_type, f"{stem}.{ext}", len(payload), img.size


def make_role_token(role: str, **extra_claims) -> str:
    payload = {
        "role": role,
        "exp": datetime.now(timezone.utc) + timedelta(days=JWT_EXPIRE_DAYS),
    }
    payload.update(extra_claims)
    return jwt.encode(payload, JWT_SECRET, algorithm=JWT_ALGO)


def make_admin_token() -> str:
    return make_role_token("admin")


def make_leader_token() -> str:
    return make_role_token("coordinator_leader", name="Kevin")


def leader_pin_matches(pin: str) -> bool:
    entered = str(pin or "")
    if LEADER_PIN:
        return hmac.compare_digest(entered, LEADER_PIN)
    expected_hash = str(LEADER_PIN_HASH or "").strip().lower()
    entered_hash = hashlib.sha256(entered.encode("utf-8")).hexdigest()
    return bool(expected_hash) and hmac.compare_digest(entered_hash, expected_hash)


def decode_bearer_token(authorization: Optional[str], missing_message: str) -> dict:
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(401, missing_message)
    token = authorization.split(" ", 1)[1]
    try:
        return jwt.decode(token, JWT_SECRET, algorithms=[JWT_ALGO])
    except JWTError:
        raise HTTPException(401, "Invalid or expired token")


async def require_admin(authorization: Optional[str] = Header(None)):
    payload = decode_bearer_token(authorization, "Missing admin token")
    if payload.get("role") != "admin":
        raise HTTPException(401, "Invalid admin token")
    return True


