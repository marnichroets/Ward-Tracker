def slugify(s: str) -> str:
    s = s.strip().lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def oid_str(doc: dict) -> dict:
    doc = dict(doc)
    doc["id"] = str(doc.pop("_id"))
    return doc


def enrich_entry(doc: dict) -> dict:
    doc = dict(doc)
    week_key = doc.get("week_key")
    day = doc.get("day")
    if week_key:
        doc["week_label"] = format_week_label(week_key)
    if week_key and day in DAY_OFFSET and not doc.get("activity_date"):
        doc["activity_date"] = activity_date_for_day(week_key, day)
    # Additive, read-time-only defaults (Phase 4): a historical document with
    # no capture_status/official_activity_type is never rewritten — this
    # dict mutation is never persisted back to Mongo. CandidateEntryOut
    # doesn't declare these fields, so FastAPI's response_model filtering
    # already keeps them out of every candidate-facing response regardless.
    doc["capture_status"] = official_capture.resolve_capture_status(doc)
    doc["official_activity_type"] = official_capture.resolve_official_activity_type(doc)
    return doc


def entry_for_response(doc: dict) -> dict:
    return enrich_entry(oid_str(doc))


async def hydrate_entry_participants(doc: dict) -> dict:
    doc = dict(doc)
    ids = normalize_participant_ids(doc.get("participant_ids"))
    doc["participant_ids"] = ids
    doc["other_participants"] = normalize_other_participants(doc.get("other_participants"))
    doc["evidence_photos"] = normalize_evidence_refs(doc.get("evidence_photos"))
    participants = []
    if ids:
        roster_docs = [oid_str(r) async for r in roster_col.find({"name_slug": {"$in": ids}})]
        by_slug = {r.get("name_slug"): r for r in roster_docs}
        for pid in ids:
            person = by_slug.get(pid)
            if person:
                participants.append({
                    "id": pid,
                    "name": person.get("name") or pid,
                    "ward": person.get("actual_ward") or person.get("ward") or "",
                    "municipality": person.get("municipality") or "",
                })
    doc["roster_participants"] = participants
    return doc


